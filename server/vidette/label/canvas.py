GLYPH_W, GLYPH_H = 5, 7
ADVANCE = GLYPH_W + 1  # one column of spacing between characters


def text_width(text: str, scale: int) -> int:
    return max(0, len(text) * ADVANCE * scale - scale)


def ascii_only(text: str) -> str:
    replacements = {"—": "-", "–": "-", "’": "'", "‘": "'", "“": '"', "”": '"', "…": "..."}
    out = "".join(replacements.get(ch, ch) for ch in text)
    return "".join(ch if ch in _GLYPHS else "?" for ch in out)


def wrap(text: str, width_chars: int, lines: int) -> list[str]:
    """Greedy word wrap into at most `lines` lines; the last one ends in '...' if cut."""
    words, out, current = ascii_only(text).split(), [], ""
    for word in words:
        candidate = f"{current} {word}".strip()
        if len(candidate) <= width_chars:
            current = candidate
            continue
        if current:
            out.append(current)
        current = word[:width_chars]
        if len(out) == lines:
            break
    if current and len(out) < lines:
        out.append(current)
    consumed = " ".join(out).split()
    if len(consumed) < len(words) and out:
        last = out[-1]
        out[-1] = (last[: max(0, width_chars - 3)].rstrip() + "...") if last else "..."
    return out[:lines]


class Canvas:
    def __init__(self, width: int, height: int, background: RGB) -> None:
        self.width = width
        self.height = height
        self.pixels = bytearray(bytes(background) * (width * height))

    def rect(self, x: int, y: int, w: int, h: int, color: RGB) -> None:
        x0, y0 = max(0, x), max(0, y)
        x1, y1 = min(self.width, x + w), min(self.height, y + h)
        if x1 <= x0 or y1 <= y0:
            return
        row = bytes(color) * (x1 - x0)
        for yy in range(y0, y1):
            start = (yy * self.width + x0) * 3
            self.pixels[start : start + len(row)] = row

    def paste_rgb(self, x: int, y: int, w: int, h: int, data: bytes) -> None:
        """Paste raw RGB24 rows (w*h*3 bytes); clipped to the canvas."""
        if len(data) != w * h * 3:
            raise ValueError(f"expected {w * h * 3} bytes for {w}x{h}, got {len(data)}")
        for row in range(h):
            yy = y + row
            if not 0 <= yy < self.height:
                continue
            x0, x1 = max(0, x), min(self.width, x + w)
            if x1 <= x0:
                return
            src = (row * w + (x0 - x)) * 3
            dst = (yy * self.width + x0) * 3
            self.pixels[dst : dst + (x1 - x0) * 3] = data[src : src + (x1 - x0) * 3]

    def text(self, x: int, y: int, text: str, *, scale: int, color: RGB) -> int:
        """Draw ASCII text with its top-left at (x, y); returns the x after the last glyph."""
        for ch in ascii_only(text):
            glyph = _GLYPHS[ch]
            for gy, row in enumerate(glyph):
                run_start = -1
                for gx in range(GLYPH_W + 1):
                    ink = gx < GLYPH_W and row[gx] == "#"
                    if ink and run_start < 0:
                        run_start = gx
                    elif not ink and run_start >= 0:
                        self.rect(
                            x + run_start * scale,
                            y + gy * scale,
                            (gx - run_start) * scale,
                            scale,
                            color,
                        )
                        run_start = -1
            x += ADVANCE * scale
        return x

    def png(self) -> bytes:
        def chunk(kind: bytes, data: bytes) -> bytes:
            body = kind + data
            return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body))

        stride = self.width * 3
        raw = b"".join(
            b"\x00" + bytes(self.pixels[row * stride : (row + 1) * stride])
            for row in range(self.height)
        )
        header = struct.pack(">IIBBBBB", self.width, self.height, 8, 2, 0, 0, 0)
        return (
            b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", header)
            + chunk(b"IDAT", zlib.compress(raw, 6))
            + chunk(b"IEND", b"")
        )
